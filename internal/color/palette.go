package color

import "math"

// Palette is a cyclic gradient: At(1) == At(0).
type Palette struct {
	Name  string
	Stops []OKLCH
}

func (p Palette) At(t float64) OKLCH {
	n := len(p.Stops)
	if n == 0 {
		return OKLCH{L: 1}
	}
	t = t - math.Floor(t)
	x := t * float64(n)
	i := int(x) % n
	return Mix(p.Stops[i], p.Stops[(i+1)%n], x-math.Floor(x))
}

